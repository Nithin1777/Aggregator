"""Generates src/web/icons.py from the lucide-static package."""
import json
import re
from pathlib import Path

SRC = Path("node_modules/lucide-static/icons")
OUT = Path("src/web/icons.py")

WANTED = [
    "search", "package", "component", "disc", "magnet", "zap", "triangle-right",
    "waypoints", "toggle-right", "microchip", "cpu", "thermometer", "plug",
    "toggle-left", "signal", "monitor", "lightbulb", "circuit-board", "bolt",
    "battery-charging", "cog", "drone", "robot-arm", "printer-3d", "shield",
    "clock", "cable", "flame", "volume-2", "camera", "wrench", "graduation-cap",
    "nut", "arrow-right", "arrow-up-right", "check", "x", "chevron-right",
    "chevron-down", "external-link", "sliders-horizontal", "store", "truck",
    "tag", "trending-up", "layers", "loader-circle", "circle-check",
    "circle-alert", "info", "sparkles", "history", "star", "indian-rupee",
    "badge-indian-rupee", "package-search", "boxes", "git-compare", "filter",
    "activity", "radio", "antenna", "bluetooth", "wifi", "gauge", "scan",
    "minus", "plus", "copy", "share-2", "type", "terminal", "database",
    "file-text", "square-stack", "blocks", "workflow", "rocket", "target",
    "bell", "menu", "arrow-left", "corner-down-left", "bookmark",
]

icons = {}
for name in WANTED:
    path = SRC / f"{name}.svg"
    if not path.exists():
        print("MISSING", name)
        continue
    svg = path.read_text(encoding="utf-8").strip()
    m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    inner = m.group(1).strip() if m else ""
    # lucide wraps content in a <g> sometimes; keep as-is
    icons[name] = " ".join(inner.split())

OUT.parent.mkdir(parents=True, exist_ok=True)
lines = [
    '"""',
    'Inline SVG icon set (Lucide, MIT licensed) used by the Aggregate web UI.',
    '',
    'Generated by scripts/generate_icons.py - do not edit by hand.',
    'Icons are inlined so they inherit `currentColor` and need no extra request.',
    '"""',
    'from typing import Dict',
    '',
    f'ICONS: Dict[str, str] = {json.dumps(icons, indent=4)}',
    '',
]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUT} with {len(icons)} icons")
